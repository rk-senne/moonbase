// portraitFor returns the ANSI portrait for an agent by name, or a fallback
func portraitFor(name string) string {
	if p, ok := Portraits[name]; ok {
		return p
	}
	return `
   ╭───────╮
   │       │
   │  ???  │
   │       │
   │  ╭─╮  │
   │  │?│  │
   │  ╰─╯  │
   ╰───────╯
   │       │
   ╰═══════╯`
}
